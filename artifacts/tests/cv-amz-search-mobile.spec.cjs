const { test, expect } = require('@playwright/test');
const path = require('node:path');
test.use({ viewport: { width: 320, height: 568 }, isMobile: true, hasTouch: true });
test('mobile search: bounded dropdown, cancellation, failure recovery and fresh prices', async ({ page }) => {
  const assets = path.resolve(__dirname, '../../wordpress/casa-viva-dropship-core/assets');
  let calls = 0;
  let fail = false;
  await page.route('http://cvamz.test/**', async route => {
    const url = new URL(route.request().url());
    if (url.pathname === '/') return route.fulfill({ contentType: 'text/html', body: '<meta name="viewport" content="width=device-width, initial-scale=1"><form role="search"><input name="s" type="search" style="width:100%;box-sizing:border-box"></form><button id="outside">Outside</button>' });
    if (url.pathname !== '/search') return route.fulfill({ status: 404 });
    calls++;
    const query = url.searchParams.get('q');
    if (query === 'slow') await new Promise(r => setTimeout(r, 900));
    if (fail) return route.fulfill({ status: 503 });
    return route.fulfill({ json: { products: [{ name: query, image: '', url: '/product', price: '$' + calls, inStock: true }] } }).catch(() => {});
  });
  await page.goto('http://cvamz.test/');
  await page.evaluate(() => { window.cvdProductSearch = { url: '/search', home: '/' }; });
  await page.addStyleTag({ path: path.join(assets, 'product-search.css') });
  await page.addScriptTag({ path: path.join(assets, 'product-search.js') });
  const input = page.getByRole('combobox');
  const list = page.getByRole('listbox');
  await input.fill('slow');
  await expect(list).toContainText('Buscando');
  await input.fill('fast');
  await expect(list).toContainText('fast');
  await page.waitForTimeout(1000);
  await expect(list).not.toContainText('slow');
  const bounds = await list.boundingBox();
  expect(bounds.x).toBeGreaterThanOrEqual(0);
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(320);
  const price = await list.locator('small').textContent();
  await input.fill('');
  await expect(list).toBeHidden();
  await input.fill('fast');
  await expect(list.locator('small')).not.toHaveText(price);
  fail = true;
  await input.fill('error');
  await expect(list).toContainText('No se pudo conectar');
  fail = false;
  await input.press('ArrowDown');
  await expect(list).toContainText('error');
  await input.fill('slow');
  await expect(list).toContainText('Buscando');
  await input.press('Escape');
  await page.waitForTimeout(1000);
  await expect(list).toBeHidden();
  await input.fill('slow');
  await expect(list).toContainText('Buscando');
  await page.locator('#outside').tap();
  await page.waitForTimeout(1000);
  await expect(list).toBeHidden();
});

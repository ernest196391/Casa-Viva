"""Transactional PostgreSQL regression for narrow Supabase Gate recovery permission.

Runs against an isolated CI postgres service, never production.
"""
import hashlib
import os
import re
import subprocess
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
MIGRATION = HERE / "sql" / "allow-guardian-gate-recovery.sql"
ROLLBACK = HERE / "sql" / "rollback-guardian-gate-recovery.sql"
BASELINE_MD5 = "962a244741ea68010e25aa8b336448ab"
APPROVED_SHA = "c5765a2088532d4940f5503f0f80aa005b85481b"

def baseline_definition():
    data = ROLLBACK.read_text()
    match = re.search(r"baseline text := '((?:''|[^'])*)';", data)
    if not match:
        raise ValueError("baseline constraint missing")
    return match.group(1).replace("''", "'")


def run_psql(sql):
    env = os.environ.copy()
    result = subprocess.run(
        ["psql", "-X", "-v", "ON_ERROR_STOP=1", "-qAt"],
        input=sql, text=True, capture_output=True, env=env, timeout=40,
        check=False,
    )
    if result.returncode:
        raise AssertionError("postgres migration regression failed: " + result.stderr[-3500:])
    return result.stdout


class GuardianGateSqlTests(unittest.TestCase):
    def test_baseline_and_exact_restriction(self):
        original = baseline_definition()
        self.assertEqual(hashlib.md5(original.encode()).hexdigest(), BASELINE_MD5)
        up = MIGRATION.read_text()
        down = ROLLBACK.read_text()
        self.assertIn(APPROVED_SHA, up)
        self.assertIn(APPROVED_SHA, down)
        self.assertIn("IS NOT DISTINCT FROM", up)
        self.assertIn("relrowsecurity", up)
        self.assertIn("rollback_history_must_be_preserved", down)
        for sql in (up, down):
            self.assertNotRegex(sql, r"(?i)\\b(?:DISABLE ROW LEVEL SECURITY|DROP POLICY|CREATE POLICY|GRANT |REVOKE )\\b")
            self.assertNotIn("local_sql_reconcile''::text) AND (args", sql)

    @unittest.skipUnless(os.environ.get("CV_SQL_TEST_PG") == "1", "isolated PostgreSQL CI required")
    def test_real_postgres_up_and_rollback(self):
        original = baseline_definition()
        up, down = MIGRATION.read_text(), ROLLBACK.read_text()
        initial = """BEGIN;
CREATE TABLE public.crm_ops_bridge (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 requested_by text NOT NULL DEFAULT 'chatgpt',
 action text NOT NULL,
 args jsonb NOT NULL DEFAULT '{}'::jsonb,
 status text NOT NULL DEFAULT 'queued'
);
ALTER TABLE public.crm_ops_bridge ADD CONSTRAINT crm_ops_bridge_action_chk """ + original + """;
ALTER TABLE public.crm_ops_bridge ENABLE ROW LEVEL SECURITY;
CREATE POLICY cv_sql_test_policy ON public.crm_ops_bridge FOR ALL TO PUBLIC USING (true) WITH CHECK (true);
"""
        assertions = """
DO $cv_test$
DECLARE
  baseline text;
  accepted integer;
BEGIN
  SELECT pg_get_constraintdef(oid) INTO baseline FROM pg_constraint
   WHERE conrelid='public.crm_ops_bridge'::regclass
     AND conname='crm_ops_bridge_action_chk';
  IF md5(baseline) = '962a244741ea68010e25aa8b336448ab' THEN
      RAISE EXCEPTION 'guardian predicate not installed';
  END IF;
  IF NOT (SELECT relrowsecurity FROM pg_class WHERE oid='public.crm_ops_bridge'::regclass)
     OR (SELECT count(*) FROM pg_policies WHERE schemaname='public' AND tablename='crm_ops_bridge') <> 1 THEN
      RAISE EXCEPTION 'RLS / policy changed';
  END IF;
  INSERT INTO public.crm_ops_bridge (action, requested_by, args)
     VALUES ('guardian_recover_gate','chatgpt','{"sha":"c5765a2088532d4940f5503f0f80aa005b85481b"}');
  GET DIAGNOSTICS accepted = ROW_COUNT;
  IF accepted <> 1 THEN RAISE EXCEPTION 'exact request rejected'; END IF;
  DELETE FROM public.crm_ops_bridge WHERE action='guardian_recover_gate';
  -- A pre-existing action remains allowed with its original argument policy.
  INSERT INTO public.crm_ops_bridge (action,requested_by,args)
     VALUES ('health','chatgpt','{"existing":"unchanged"}');
  DELETE FROM public.crm_ops_bridge WHERE action='health';
  BEGIN
     INSERT INTO public.crm_ops_bridge (action,requested_by,args)
     VALUES ('guardian_recover_gate','chatgpt','{"sha":"a"}');
     RAISE EXCEPTION 'wrong SHA was accepted';
  EXCEPTION WHEN check_violation THEN NULL;
  END;
  BEGIN
     INSERT INTO public.crm_ops_bridge (action,requested_by,args)
     VALUES ('guardian_recover_gate','chatgpt','{"sha":"c5765a2088532d4940f5503f0f80aa005b85481b","extra":true}');
     RAISE EXCEPTION 'extra keys accepted';
  EXCEPTION WHEN check_violation THEN NULL;
  END;
  BEGIN
     INSERT INTO public.crm_ops_bridge (action,requested_by,args)
     VALUES ('guardian_recover_gate','not-chatgpt','{"sha":"c5765a2088532d4940f5503f0f80aa005b85481b"}');
     RAISE EXCEPTION 'unapproved requester accepted';
  EXCEPTION WHEN check_violation THEN NULL;
  END;
  BEGIN
     INSERT INTO public.crm_ops_bridge (action,requested_by,args)
     VALUES ('local_sql_reconcile','chatgpt','{}');
     RAISE EXCEPTION 'local SQL reconcile was accepted';
  EXCEPTION WHEN check_violation THEN NULL;
  END;
END $cv_test$;
"""
        finish = """
DO $cv_after$
BEGIN
 IF (SELECT md5(pg_get_constraintdef(oid)) FROM pg_constraint
      WHERE conrelid='public.crm_ops_bridge'::regclass
      AND conname='crm_ops_bridge_action_chk') <> '962a244741ea68010e25aa8b336448ab' THEN
    RAISE EXCEPTION 'original allowlist not restored';
 END IF;
 IF NOT (SELECT relrowsecurity FROM pg_class WHERE oid='public.crm_ops_bridge'::regclass)
     OR (SELECT count(*) FROM pg_policies WHERE schemaname='public' AND tablename='crm_ops_bridge') <> 1 THEN
    RAISE EXCEPTION 'rollback changed RLS/policy';
 END IF;
END $cv_after$;
ROLLBACK;
"""
        run_psql(initial + up + assertions + down + finish)


if __name__ == "__main__":
    unittest.main()

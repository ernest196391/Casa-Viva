"""Isolated PostgreSQL integration test for CV-AUTO-002 probe authorization.

Uses only the CI postgres service. Never connects to live Supabase.
"""
import os
import subprocess
import unittest
from pathlib import Path
import re

def baseline_definition():
    data=(Path(__file__).resolve().parent/'sql/rollback-guardian-gate-recovery.sql').read_text()
    m=re.search(r"baseline text := '((?:''|[^'])*)';", data)
    if not m: raise ValueError('baseline not found')
    return m.group(1).replace("''", "'")

HERE=Path(__file__).resolve().parent
GATE=(HERE/"sql/allow-guardian-gate-recovery.sql").read_text()
UP=(HERE/"sql/allow-guardian-isolation-probe.sql").read_text()
DOWN=(HERE/"sql/rollback-guardian-isolation-probe.sql").read_text()

def pg(sql, success=True):
    r=subprocess.run(["psql","-X","-qAt","-v","ON_ERROR_STOP=1"],input=sql,text=True,
                     capture_output=True,timeout=40,check=False)
    if success and r.returncode != 0:
        raise AssertionError("postgres failed: "+r.stderr[-3000:])
    if not success and r.returncode == 0:
        raise AssertionError("expected postgres failure")
    return r

@unittest.skipUnless(os.environ.get("CV_SQL_TEST_PG")=="1","isolated postgres required")
class IsolationProbeSQLIntegration(unittest.TestCase):
    def test_allowed_denied_rollback(self):
        old=baseline_definition()
        init="""BEGIN;
CREATE TABLE public.crm_ops_bridge (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 requested_by text NOT NULL DEFAULT 'chatgpt',
 action text NOT NULL,
 args jsonb NOT NULL DEFAULT '{}'::jsonb,
 status text NOT NULL DEFAULT 'queued'
);
ALTER TABLE public.crm_ops_bridge ADD CONSTRAINT crm_ops_bridge_action_chk """+old+""";
ALTER TABLE public.crm_ops_bridge ENABLE ROW LEVEL SECURITY;
CREATE POLICY cv_test_policy ON public.crm_ops_bridge FOR ALL TO PUBLIC USING (true) WITH CHECK (true);
"""
        check_baseline="""
DO $test$
BEGIN
 IF (SELECT md5(pg_get_constraintdef(oid)) FROM pg_constraint
 WHERE conrelid='public.crm_ops_bridge'::regclass
 AND conname='crm_ops_bridge_action_chk') <> '3e08e16a5a93e1313a96caa31229745a'
 THEN RAISE EXCEPTION 'expected baseline missing'; END IF;
END $test$;
"""
        checks="""
DO $test$
DECLARE n integer;
BEGIN
 INSERT INTO public.crm_ops_bridge(action,requested_by,args)
 VALUES('guardian_isolation_probe','chatgpt','{}'::jsonb);
 GET DIAGNOSTICS n=ROW_COUNT;
 IF n<>1 THEN RAISE EXCEPTION 'valid probe rejected'; END IF;
 DELETE FROM public.crm_ops_bridge WHERE action='guardian_isolation_probe';
 INSERT INTO public.crm_ops_bridge(action,requested_by,args)
 VALUES('health','chatgpt','{"keep":"legacy"}');
 DELETE FROM public.crm_ops_bridge WHERE action='health';
 BEGIN
  INSERT INTO public.crm_ops_bridge(action,requested_by,args)
  VALUES('guardian_isolation_probe','chatgpt','{"command":"shell"}');
  RAISE EXCEPTION 'extra arguments allowed';
 EXCEPTION WHEN check_violation THEN NULL;
 END;
 BEGIN
  INSERT INTO public.crm_ops_bridge(action,requested_by,args)
  VALUES('guardian_isolation_probe','other','{}');
  RAISE EXCEPTION 'unapproved requester allowed';
 EXCEPTION WHEN check_violation THEN NULL;
 END;
 BEGIN
  INSERT INTO public.crm_ops_bridge(action,requested_by,args)
  VALUES('local_sql_reconcile','chatgpt','{}');
  RAISE EXCEPTION 'unrelated action allowed';
 EXCEPTION WHEN check_violation THEN NULL;
 END;
 IF (SELECT count(*) FROM pg_policies
 WHERE schemaname='public' AND tablename='crm_ops_bridge')<>1
 OR (SELECT relrowsecurity FROM pg_class WHERE oid='public.crm_ops_bridge'::regclass) IS DISTINCT FROM true
 THEN RAISE EXCEPTION 'RLS drift'; END IF;
END $test$;
"""
        pg(init+GATE+check_baseline+UP+checks+"""
DO $debug_constraint$
BEGIN
 RAISE NOTICE 'ISOLATION INSTALLED: %',
  (SELECT pg_get_constraintdef(oid) FROM pg_constraint
   WHERE conrelid='public.crm_ops_bridge'::regclass
   AND conname='crm_ops_bridge_action_chk');
END $debug_constraint$;
"""+DOWN+check_baseline+"ROLLBACK;")

    def test_baseline_drift_refused(self):
        pg("""BEGIN;
CREATE TABLE public.crm_ops_bridge(action text,requested_by text,args jsonb);
ALTER TABLE public.crm_ops_bridge ADD CONSTRAINT crm_ops_bridge_action_chk CHECK (action='health');
ALTER TABLE public.crm_ops_bridge ENABLE ROW LEVEL SECURITY;
"""+UP+"ROLLBACK;",success=False)

if __name__=="__main__":
    unittest.main()
